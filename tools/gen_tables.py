#!/usr/bin/env python3
"""Generate Rust tables from the original sources.

Reads upstream/src/passw/diceware8k.c (8192-word list) and
upstream/src/passw/PhoneticTrigram.h (trigram frequencies) and writes
crates/pwtech-core/src/passw/tables.rs.

Usage: python3 -I tools/gen_tables.py <repo-root>
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
dice_src = (root / "upstream/src/passw/diceware8k.c").read_text(encoding="latin-1")
body = dice_src[dice_src.index("{", dice_src.index("Dicewds8k")) + 1: dice_src.index("};")]
words = []
for line in body.splitlines():
    m = re.match(r'\s*\{?\s*"((?:[^"\\]|\\.)*)"', line)
    if not m:
        continue
    w = m.group(1)
    w = re.sub(r"\\(.)", r"\1", w)
    words.append(w)
assert len(words) == 8192, len(words)

tri_src = (root / "upstream/src/passw/PhoneticTrigram.h").read_text(encoding="latin-1")
sigma = int(re.search(r"PHONETIC_SIGMA\s*=\s*(\d+)", tri_src).group(1))
entropy = re.search(r"PHONETIC_ENTROPY\s*=\s*([0-9.]+)", tri_src).group(1)
arr = tri_src[tri_src.index("{", tri_src.index("PHONETIC_TRIS[")) + 1: tri_src.rindex("}")]
tris = [int(x) for x in re.findall(r"\d+", arr)]
assert len(tris) == 17576, len(tris)
assert sum(tris) == sigma, (sum(tris), sigma)

def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = []
out.append("// Generated by tools/gen_tables.py from upstream/src/passw/diceware8k.c and")
out.append("// upstream/src/passw/PhoneticTrigram.h. Do not edit.")
out.append("//")
out.append("// diceware8k list by Arnold G. Reinhold (http://www.diceware.com).")
out.append("")
out.append("/// Built-in word list (`getDiceWd()`), 8192 words.")
out.append("pub static DICEWARE8K: [&str; 8192] = [")
for i in range(0, len(words), 8):
    out.append("    " + ", ".join(rs_str(w) for w in words[i:i + 8]) + ",")
out.append("];")
out.append("")
out.append(f"/// Sum of all built-in trigram frequencies (`PHONETIC_SIGMA`).")
out.append(f"pub const PHONETIC_SIGMA: u32 = {sigma};")
out.append(f"/// Entropy per character of the built-in trigrams (`PHONETIC_ENTROPY`).")
out.append(f"pub const PHONETIC_ENTROPY: f64 = {entropy};")
out.append("")
out.append("/// Built-in trigram frequencies (`PHONETIC_TRIS`), index 676*a + 26*b + c.")
out.append("pub static PHONETIC_TRIS: [u16; 17576] = [")
for i in range(0, len(tris), 26):
    out.append("    " + ", ".join(str(t) for t in tris[i:i + 26]) + ",")
out.append("];")
dest = root / "crates/pwtech-core/src/passw/tables.rs"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(words)} words, {len(tris)} trigrams, sigma {sigma} -> {dest}")
print("non-alnum words:", [w for w in words if not w.isalnum()][:40])
